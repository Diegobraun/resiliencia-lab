create table if not exists idempotencia (
    cliente varchar(100) not null,
    chave varchar(100) not null,
    hash_requisicao varchar(64) not null,
    status varchar(20) not null,
    status_http int,
    resposta clob,
    criado_em timestamp not null,
    primary key (cliente, chave)
);

create table if not exists transferencia (
    id varchar(36) primary key,
    cliente varchar(100) not null,
    conta_origem varchar(50) not null,
    conta_destino varchar(50) not null,
    valor decimal(19, 2) not null,
    status varchar(30) not null,
    motivo varchar(500),
    celula int not null,
    criado_em timestamp not null,
    atualizado_em timestamp not null
);

create index if not exists idx_transferencia_status on transferencia (status, atualizado_em);

create table if not exists outbox (
    id bigint generated by default as identity primary key,
    evento_id varchar(36) not null unique,
    agregado_id varchar(36) not null,
    tipo varchar(60) not null,
    payload clob not null,
    criado_em timestamp not null,
    publicado_em timestamp
);

create index if not exists idx_outbox_pendente on outbox (publicado_em, id);
